'use strict';

const test = require('node:test');
const assert = require('node:assert/strict');
const { installRichTableRelay } = require('../src/Plugin/richRelay');

function createSocket() {
    const calls = [];
    const sock = {
        calls,
        sendMessage: async (...args) => {
            calls.push({ type: 'sendMessage', args });
            return 'ordinary-result';
        },
        sendPlogmeMessage: async (...args) => {
            calls.push({ type: 'sendPlogmeMessage', args });
            return 'rich-result';
        },
    };
    return sock;
}

test('legacy CODY table messages go through plogme rich relay with edit enabled', async () => {
    const sock = createSocket();
    installRichTableRelay(sock);
    const content = {
        headerText: '## Report',
        contentText: '---',
        title: 'Results',
        table: [['Name', 'Value'], ['Active', 12]],
        footerText: 'Generated by CODY',
    };
    const quoted = { key: { id: 'quoted-message' } };
    const options = { quoted, useCachedGroupMetadata: true };

    const result = await sock.sendMessage('123@g.us', content, options);

    assert.equal(result, 'rich-result');
    assert.equal(sock.calls.length, 1);
    assert.equal(sock.calls[0].type, 'sendPlogmeMessage');
    assert.deepEqual(sock.calls[0].args, [
        '123@g.us',
        content,
        quoted,
        { quoted, useCachedGroupMetadata: true, renderRichResponse: true },
    ]);
});

test('ordinary and non-table message shapes keep the original sendMessage path', async () => {
    const sock = createSocket();
    installRichTableRelay(sock);

    assert.equal(await sock.sendMessage('123@s.whatsapp.net', { text: 'hello' }), 'ordinary-result');
    assert.equal(await sock.sendMessage(['123@s.whatsapp.net'], { table: [['A', 'B']] }), 'ordinary-result');
    assert.equal(await sock.sendMessage('123@s.whatsapp.net', { table: [['A', 'B']], image: Buffer.from('x') }), 'ordinary-result');

    assert.deepEqual(sock.calls.map(call => call.type), ['sendMessage', 'sendMessage', 'sendMessage']);
});

test('adapter installation is idempotent', () => {
    const sock = createSocket();
    assert.equal(installRichTableRelay(sock), true);
    const wrappedSendMessage = sock.sendMessage;
    assert.equal(installRichTableRelay(sock), false);
    assert.equal(sock.sendMessage, wrappedSendMessage);
});

test('older sockets without sendPlogmeMessage safely retain their original behavior', async () => {
    const sock = {
        sendMessage: async () => 'legacy-result',
    };
    installRichTableRelay(sock);
    assert.equal(await sock.sendMessage('123@g.us', { table: [['A', 'B']] }), 'legacy-result');
});
